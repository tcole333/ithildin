"""Local SQLite/FTS5 index for the public MuckRock API v2 corpus.

The index deliberately keeps MuckRock request metadata, communication bodies,
and file metadata separate.  Communication ``files`` references provide the
join from a released file back to its request.  A blank file ``doc_id`` is
treated as *DocumentCloud-unlinked* rather than proof that no duplicate exists
elsewhere in DocumentCloud.
"""

from __future__ import annotations

import json
import re
import sqlite3
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable, Iterable


DEFAULT_INDEX_DB = Path("datasets/muckrock_index.db")
PAGE_SIZE = 100
COLLECTIONS = (
    "requests",
    "communications",
    "files",
    "agencies",
    "jurisdictions",
)
COLLECTION_ORDERING = {
    "requests": "datetime_submitted",
    "communications": "datetime",
    "files": "datetime",
    "agencies": "name",
    "jurisdictions": "name",
}


