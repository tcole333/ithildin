def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _get(obj, name, default=None):
    if isinstance(obj, dict):
        return obj.get(name, default)
    return getattr(obj, name, default)


def _object_id(value):
    if value is None or isinstance(value, (int, str)):
        return value
    return _get(value, "id", value)


def _text(value) -> str:
    return "" if value is None else str(value)


def _optional_text(value) -> str | None:
    return None if value is None else str(value)


def _json(value) -> str:
    return json.dumps(value if value is not None else [], default=str, sort_keys=True)


def connect_index(db_path: str | Path = DEFAULT_INDEX_DB) -> sqlite3.Connection:
    """Open an index database and ensure the schema exists."""
    path = Path(db_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA journal_mode=WAL")
    connection.execute("PRAGMA synchronous=NORMAL")
    connection.executescript(SCHEMA)
    columns = {
        row[1] for row in connection.execute("PRAGMA table_info(crawl_state)")
    }
    if "ordering" not in columns:
        connection.execute("ALTER TABLE crawl_state ADD COLUMN ordering TEXT")
    return connection


def _upsert_request(connection: sqlite3.Connection, obj, indexed_at: str) -> None:
    connection.execute(
        """
        INSERT INTO requests(
            id, title, requested_docs, slug, status, agency_id, user_id,
            embargo_status, datetime_submitted, datetime_updated, datetime_done,
            tracking_id, price, tags_json, indexed_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(id) DO UPDATE SET
            title=excluded.title,
            requested_docs=excluded.requested_docs,
            slug=excluded.slug,
            status=excluded.status,
            agency_id=excluded.agency_id,
            user_id=excluded.user_id,
            embargo_status=excluded.embargo_status,
            datetime_submitted=excluded.datetime_submitted,
            datetime_updated=excluded.datetime_updated,
            datetime_done=excluded.datetime_done,
            tracking_id=excluded.tracking_id,
            price=excluded.price,
            tags_json=excluded.tags_json,
            indexed_at=excluded.indexed_at
        """,
        (
            _get(obj, "id"),
            _text(_get(obj, "title")),
            _text(_get(obj, "requested_docs")),
            _text(_get(obj, "slug")),
            _text(_get(obj, "status")),
            _object_id(_get(obj, "agency")),
            _object_id(_get(obj, "user")),
            _text(_get(obj, "embargo_status")),
            _text(_get(obj, "datetime_submitted")),
            _text(_get(obj, "datetime_updated")),
            _text(_get(obj, "datetime_done")),
            _text(_get(obj, "tracking_id")),
            _text(_get(obj, "price")),
            _json(_get(obj, "tags")),
            indexed_at,
        ),
    )


def _upsert_communication(
    connection: sqlite3.Connection, obj, indexed_at: str
) -> None:
    communication_id = _get(obj, "id")
    connection.execute(
        """
        INSERT INTO communications(
            id, request_id, from_user_id, to_user_id, subject, datetime,
            response, autogenerated, communication_body, status, indexed_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(id) DO UPDATE SET
            request_id=excluded.request_id,
            from_user_id=excluded.from_user_id,
            to_user_id=excluded.to_user_id,
            subject=excluded.subject,
            datetime=excluded.datetime,
            response=excluded.response,
            autogenerated=excluded.autogenerated,
            communication_body=excluded.communication_body,
            status=excluded.status,
            indexed_at=excluded.indexed_at
        """,
        (
            communication_id,
            _object_id(_get(obj, "foia")),
            _object_id(_get(obj, "from_user")),
            _object_id(_get(obj, "to_user")),
            _text(_get(obj, "subject")),
            _text(_get(obj, "datetime")),
            int(bool(_get(obj, "response", False))),
            int(bool(_get(obj, "autogenerated", False))),
            _text(_get(obj, "communication")),
            _text(_get(obj, "status")),
            indexed_at,
        ),
    )
    connection.execute(
        "DELETE FROM communication_files WHERE communication_id = ?",
        (communication_id,),
    )
    for file_ref in _get(obj, "files", []) or []:
        file_id = _object_id(file_ref)
        if file_id is not None:
            connection.execute(
                """
                INSERT OR IGNORE INTO communication_files(communication_id, file_id)
                VALUES (?, ?)
                """,
                (communication_id, file_id),
            )


