UPSERT_HANDLERS = {
    "requests": _upsert_request,
    "communications": _upsert_communication,
    "files": _upsert_file,
    "agencies": _upsert_agency,
    "jurisdictions": _upsert_jurisdiction,
}


def ingest_page(
    connection: sqlite3.Connection, collection: str, rows: Iterable
) -> int:
    """Upsert one API page and return its row count."""
    handler = UPSERT_HANDLERS[collection]
    indexed_at = _now()
    count = 0
    for row in rows:
        handler(connection, row, indexed_at)
        count += 1
    return count


def _crawl_state(connection: sqlite3.Connection, collection: str):
    return connection.execute(
        "SELECT * FROM crawl_state WHERE collection = ?", (collection,)
    ).fetchone()


def _set_crawl_state(
    connection: sqlite3.Connection,
    *,
    collection: str,
    ordering: str,
    next_page: int,
    total_count: int | None,
    rows_seen: int,
    completed: bool,
    started_at: str,
) -> None:
    now = _now()
    connection.execute(
        """
        INSERT INTO crawl_state(
            collection, ordering, next_page, total_count, rows_seen, completed,
            started_at, updated_at, completed_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(collection) DO UPDATE SET
            ordering=excluded.ordering,
            next_page=excluded.next_page,
            total_count=excluded.total_count,
            rows_seen=excluded.rows_seen,
            completed=excluded.completed,
            started_at=excluded.started_at,
            updated_at=excluded.updated_at,
            completed_at=excluded.completed_at
        """,
        (
            collection,
            ordering,
            next_page,
            total_count,
            rows_seen,
            int(completed),
            started_at,
            now,
            now if completed else None,
        ),
    )


def crawl_index(
    client,
    *,
    db_path: str | Path = DEFAULT_INDEX_DB,
    collections: Iterable[str] = COLLECTIONS,
    max_pages: int = 0,
    delay: float = 1.0,
    restart: bool = False,
    progress: Callable[[str, int, int, int | None], None] | None = None,
) -> dict:
    """Crawl selected API collections into a resumable local index.

    Collections are interleaved so each endpoint remains near the official
    wrapper's conservative per-endpoint rate while aggregate requests remain at
    or below the API's documented one-request-per-second average.
    """
    selected = list(dict.fromkeys(collections))
    invalid = sorted(set(selected) - set(COLLECTIONS))
    if invalid:
        raise ValueError(f"Unknown MuckRock collections: {', '.join(invalid)}")
    if max_pages < 0:
        raise ValueError("max_pages cannot be negative")
    if delay < 0:
        raise ValueError("delay cannot be negative")

    connection = connect_index(db_path)
    started = _now()
    states: list[dict] = []
    summaries: dict[str, dict] = {}
    try:
        if restart:
            placeholders = ",".join("?" for _ in selected)
            connection.execute(
                f"DELETE FROM crawl_state WHERE collection IN ({placeholders})",
                selected,
            )
            connection.commit()

        for collection in selected:
            saved = _crawl_state(connection, collection)
            ordering = COLLECTION_ORDERING[collection]
            saved_ordering = saved["ordering"] if saved else None
            if saved and saved_ordering != ordering:
                raise ValueError(
                    f"Saved {collection} cursor uses ordering {saved_ordering!r}; "
                    f"current ordering is {ordering!r}. Re-run with --restart."
                )
            if saved and saved["completed"]:
                summaries[collection] = {
                    "pages": 0,
                    "rows": 0,
                    "total": saved["total_count"],
                    "completed": True,
                    "next_page": saved["next_page"],
                    "skipped": "already complete; use --restart to refresh",
                }
                continue

            next_page = int(saved["next_page"]) if saved else 1
            rows_seen = int(saved["rows_seen"]) if saved else 0
            crawl_started = saved["started_at"] if saved else started
            state = {
                "collection": collection,
                "ordering": ordering,
                "page": next_page,
                "run_pages": 0,
                "run_rows": 0,
                "rows_seen": rows_seen,
                "total": saved["total_count"] if saved else None,
                "started_at": crawl_started,
            }
            states.append(state)
            summaries[collection] = {
                "pages": 0,
                "rows": 0,
                "total": state["total"],
                "completed": False,
                "next_page": next_page,
            }

        last_request_started: float | None = None
        while states:
            for state in list(states):
                if max_pages and state["run_pages"] >= max_pages:
                    states.remove(state)
                    continue

                if last_request_started is not None:
                    remaining = delay - (time.monotonic() - last_request_started)
                    if remaining > 0:
                        time.sleep(remaining)

                collection = state["collection"]
                page = state["page"]
                manager = getattr(client, collection)
                last_request_started = time.monotonic()
                api_results = manager.list(
                    page=page,
                    page_size=PAGE_SIZE,
                    ordering=state["ordering"],
                )
                page_rows = list(api_results.results)
                total = getattr(api_results, "count", None)
                if total is not None:
                    total = int(total)

                with connection:
                    row_count = ingest_page(connection, collection, page_rows)
                    state["run_pages"] += 1
                    state["run_rows"] += row_count
                    state["rows_seen"] += row_count
                    state["total"] = total
                    completed = not bool(getattr(api_results, "next_url", None))
                    next_page = page + 1
                    _set_crawl_state(
                        connection,
                        collection=collection,
                        ordering=state["ordering"],
                        next_page=next_page,
                        total_count=total,
                        rows_seen=state["rows_seen"],
                        completed=completed,
                        started_at=state["started_at"],
                    )

                if progress:
                    progress(collection, page, row_count, total)

                summary = summaries[collection]
                summary.update(
                    {
                        "pages": state["run_pages"],
                        "rows": state["run_rows"],
                        "total": total,
                        "completed": completed,
                        "next_page": next_page,
                    }
                )
                if completed:
                    states.remove(state)
                else:
                    state["page"] = next_page

        return {
            "db": str(Path(db_path)),
            "page_size": PAGE_SIZE,
            "collections": summaries,
            "pages_fetched": sum(item["pages"] for item in summaries.values()),
            "rows_upserted": sum(item["rows"] for item in summaries.values()),
            "started_at": started,
            "finished_at": _now(),
        }
    finally:
        connection.close()


def _fts_query(query: str | None) -> str | None:
    if not query:
        return None
    tokens = re.findall(r"[^\W_]+(?:[-./@][^\W_]+)*", query, flags=re.UNICODE)
    if not tokens:
        return None
    return " AND ".join(f'"{token.replace(chr(34), chr(34) * 2)}"' for token in tokens)


def _excerpt(text: str, query: str | None, width: int = 500) -> str:
    collapsed = re.sub(r"\s+", " ", text or "").strip()
    if len(collapsed) <= width:
        return collapsed
    start = 0
    if query:
        terms = re.findall(r"[^\W_]+", query, flags=re.UNICODE)
        lowered = collapsed.lower()
        positions = [lowered.find(term.lower()) for term in terms]
        positions = [position for position in positions if position >= 0]
        if positions:
            start = max(0, min(positions) - width // 3)
    excerpt = collapsed[start : start + width]
    return ("…" if start else "") + excerpt + (
        "…" if start + width < len(collapsed) else ""
    )


def search_index(
    *,
    db_path: str | Path = DEFAULT_INDEX_DB,
    query: str | None = None,
    without_documentcloud: bool = False,
    response_only: bool = False,
    agency_id: int | None = None,
    limit: int = 100,
) -> list[dict]:
    """Search indexed requests/correspondence/file metadata, returning files."""
    path = Path(db_path)
    if not path.exists():
        raise FileNotFoundError(f"MuckRock index does not exist: {path}")
    if limit < 1:
        raise ValueError("limit must be at least 1")

    connection = connect_index(path)
    try:
        fts_query = _fts_query(query)
        params: dict[str, object] = {"limit": limit}
        if fts_query:
            params["fts_query"] = fts_query
            matched_files = """
                SELECT cf.file_id
                FROM requests_fts
                JOIN communications c ON c.request_id = requests_fts.rowid
                JOIN communication_files cf ON cf.communication_id = c.id
                WHERE requests_fts MATCH :fts_query
                UNION
                SELECT cf.file_id
                FROM communications_fts
                JOIN communication_files cf
                    ON cf.communication_id = communications_fts.rowid
                WHERE communications_fts MATCH :fts_query
                UNION
                SELECT rowid AS file_id
                FROM files_fts
                WHERE files_fts MATCH :fts_query
            """
        else:
            matched_files = "SELECT id AS file_id FROM files"

        filters = []
        if without_documentcloud:
            filters.append("NULLIF(TRIM(f.doc_id), '') IS NULL")
        if response_only:
            filters.append("c.response = 1")
        if agency_id is not None:
            filters.append("r.agency_id = :agency_id")
            params["agency_id"] = agency_id
        where = "WHERE " + " AND ".join(filters) if filters else ""

        rows = connection.execute(
            f"""
            WITH matched_files(file_id) AS ({matched_files})
            SELECT DISTINCT
                f.id AS file_id,
                f.title AS file_title,
                f.url AS file_url,
                f.pages,
                f.datetime AS file_datetime,
                f.source AS file_source,
                f.description AS file_description,
                f.doc_id,
                CASE WHEN NULLIF(TRIM(f.doc_id), '') IS NULL
                     THEN 1 ELSE 0 END AS documentcloud_unlinked,
                c.id AS communication_id,
                c.datetime AS communication_datetime,
                c.subject AS communication_subject,
                c.communication_body,
                c.response,
                r.id AS request_id,
                r.title AS request_title,
                r.requested_docs,
                r.slug AS request_slug,
                r.status AS request_status,
                r.agency_id,
                a.name AS agency_name
            FROM matched_files mf
            JOIN files f ON f.id = mf.file_id
            JOIN communication_files cf ON cf.file_id = f.id
            JOIN communications c ON c.id = cf.communication_id
            LEFT JOIN requests r ON r.id = c.request_id
            LEFT JOIN agencies a ON a.id = r.agency_id
            {where}
            ORDER BY
                COALESCE(NULLIF(f.datetime, ''), NULLIF(c.datetime, ''),
                         NULLIF(r.datetime_updated, '')) DESC,
                f.id DESC
            LIMIT :limit
            """,
            params,
        ).fetchall()

        results = []
        for row in rows:
            result = dict(row)
            result["documentcloud_unlinked"] = bool(
                result["documentcloud_unlinked"]
            )
            result["response"] = bool(result["response"])
            result["communication_excerpt"] = _excerpt(
                result.pop("communication_body"), query
            )
            result["requested_docs_excerpt"] = _excerpt(
                result.pop("requested_docs"), query
            )
            request_id = result.get("request_id")
            result["request_url"] = (
                f"https://www.muckrock.com/foi/request/{request_id}/"
                if request_id is not None
                else ""
            )
            results.append(result)
        return results
    finally:
        connection.close()


def index_stats(db_path: str | Path = DEFAULT_INDEX_DB) -> dict:
    """Return corpus counts, DocumentCloud linkage counts, and crawl cursors."""
    path = Path(db_path)
    if not path.exists():
        raise FileNotFoundError(f"MuckRock index does not exist: {path}")
    connection = connect_index(path)
    try:
        counts = {
            table: connection.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
            for table in (
                "requests",
                "communications",
                "files",
                "communication_files",
                "agencies",
                "jurisdictions",
            )
        }
        linkage = dict(
            connection.execute(
                """
                SELECT
                    SUM(CASE WHEN NULLIF(TRIM(doc_id), '') IS NULL
                             THEN 1 ELSE 0 END) AS documentcloud_unlinked,
                    SUM(CASE WHEN NULLIF(TRIM(doc_id), '') IS NOT NULL
                             THEN 1 ELSE 0 END) AS documentcloud_linked
                FROM files
                """
            ).fetchone()
        )
        linkage["unlinked_response_files"] = connection.execute(
            """
            SELECT COUNT(DISTINCT f.id)
            FROM files f
            JOIN communication_files cf ON cf.file_id = f.id
            JOIN communications c ON c.id = cf.communication_id
            WHERE NULLIF(TRIM(f.doc_id), '') IS NULL AND c.response = 1
            """
        ).fetchone()[0]
        linkage["file_records_without_communication"] = connection.execute(
            """
            SELECT COUNT(*) FROM files f
            WHERE NOT EXISTS (
                SELECT 1 FROM communication_files cf WHERE cf.file_id = f.id
            )
            """
        ).fetchone()[0]
        linkage["unresolved_file_references"] = connection.execute(
            """
            SELECT COUNT(*) FROM communication_files cf
            LEFT JOIN files f ON f.id = cf.file_id
            WHERE f.id IS NULL
            """
        ).fetchone()[0]
        crawl = [
            dict(row)
            for row in connection.execute(
                "SELECT * FROM crawl_state ORDER BY collection"
            ).fetchall()
        ]
        for row in crawl:
            row["completed"] = bool(row["completed"])
        return {
            "db": str(path),
            "counts": counts,
            "documentcloud_linkage": linkage,
            "crawl_state": crawl,
        }
    finally:
        connection.close()
